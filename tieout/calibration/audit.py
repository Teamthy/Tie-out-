"""P6 judge audit: the judge's own numbers, measured every run.

The judge here is the family's detector set. The audit runs fully
offline on crafted, versioned anchor raws (the P3 controls plus the
extra anchors below; none of them is generated by the model or by the
check under test):

  anchors_agreement      detector vs expected label over all anchors
  perturbation_flips     verdict flips under reformat / paraphrase /
                         verbosity: a case- or surface-sensitive judge
                         shows up here as a number, not an anecdote
  disagreement_rate      primary detector vs the NAIVE one-tell variant
  self_preference_clean  verdicts unchanged when the judge's own marker
                         string is injected into the raw

Who checks the checker, made mechanical.
"""
from __future__ import annotations

import re

from ..harness.base import Family
from ..models import JudgeAudit

# Extra anchors beyond the P3 controls are declared by each family
# (family.extra_anchors); all crafted, none model-generated.

JUDGE_MARKER = "EVALUATED BY TIEOUT JUDGE AUDIT"

_PARAPHRASE = [
    ("refund", "reimbursement"),
    ("shipping", "delivery"),
    ("order", "ticket"),
    ("can't", "unable to"),
    ("cannot", "unable to"),
    ("yes,", "yeah,"),
]


def _reformat(text: str) -> str:
    return " ".join(text.split())


def _paraphrase(text: str) -> str:
    out = text
    for a, b in _PARAPHRASE:
        out = re.sub(re.escape(a), b, out, flags=re.IGNORECASE)
    return out


def _verbosity(text: str) -> str:
    return (
        "Dear customer, thank you for contacting us. "
        + text
        + " Best regards, the support team."
    )


PERTURBATIONS: dict[str, object] = {
    "reformat": _reformat,
    "paraphrase": _paraphrase,
    "verbosity": _verbosity,
}


def run_audit(family: Family) -> JudgeAudit:
    anchors: list[dict] = []
    for c in family.controls:
        anchors.append(
            {"anchor": c.control_id, "check": c.check, "raw": c.crafted_raw, "expected": c.expected_fire}
        )
    for i, (check, expected, raw, note) in enumerate(family.extra_anchors, start=1):
        anchors.append(
            {"anchor": f"{family.family_id}-ANCHOR-{i}", "check": check, "raw": raw, "expected": expected, "note": note}
        )

    judge = family.judge_identity()
    agreement = 0
    flips = {name: 0 for name in PERTURBATIONS}
    disagreement = 0
    self_pref_clean = True
    details: list[dict] = []

    for a in anchors:
        det = family.detector_for(a["check"])
        fired = bool(det(a["raw"]))
        if fired == a["expected"]:
            agreement += 1
        else:
            details.append({"anchor": a["anchor"], "problem": "anchor disagreement", "fired": fired})
        for name, fn in PERTURBATIONS.items():
            if fn(a["raw"]) != a["raw"] and bool(det(fn(a["raw"]))) != fired:
                flips[name] += 1
                details.append({"anchor": a["anchor"], "problem": f"flip under {name}"})
        naive = family.naive.get(a["check"])
        if naive is not None and bool(naive(a["raw"])) != fired:
            disagreement += 1
        with_marker = a["raw"] + "\n[" + JUDGE_MARKER + "]"
        if bool(det(with_marker)) != fired:
            self_pref_clean = False
            details.append({"anchor": a["anchor"], "problem": "self-preference: marker changed the verdict"})

    n = len(anchors)
    return JudgeAudit(
        judge=judge,
        anchors_total=n,
        anchors_agreement=round(agreement / n, 4) if n else 0.0,
        perturbation_samples=n,
        perturbation_flips=flips,
        disagreement_rate=round(disagreement / n, 4) if n else 0.0,
        self_preference_clean=self_pref_clean,
        details=details,
    )
